def get_venues_by_tier(tier: VenueTier) -> list:
    """Get all venues of a specific tier"""
    all_venues = get_all_venues()
    return [v for v in all_venues if v.tier == tier]


def get_venues_by_continent(continent: str) -> list:
    """Get all venues in a continent"""
    all_venues = get_all_venues()
    return [v for v in all_venues if v.continent == continent]


def get_venue_by_id(venue_id: str) -> Venue:
    """Get a specific venue by ID"""
    all_venues = get_all_venues()
    for venue in all_venues:
        if venue.id == venue_id:
            return venue
    return None
